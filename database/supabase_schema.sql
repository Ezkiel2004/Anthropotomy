CREATE TRIGGER trg_assessments_updated   BEFORE UPDATE ON public.assessments   FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE OR REPLACE FUNCTION public.set_last_updated() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  NEW.last_updated := now();
  RETURN NEW;
END $$;
CREATE TRIGGER trg_progress_summary_updated BEFORE UPDATE ON public.student_progress_summary FOR EACH ROW EXECUTE FUNCTION public.set_last_updated();

-- Security: Supabase exposes the public schema through its REST API.
-- RLS on with no policies blocks the anon/authenticated API keys from every
-- table (password hashes, student records). The PHP app connects as the
-- database owner, which bypasses RLS.
DO $$
DECLARE t text;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'public' LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;
