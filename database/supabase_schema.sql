-- Anthropotomy – PostgreSQL (Supabase) schema
-- Converted from the live MySQL schema (anatomiq_db). Structure only, no data.
-- The PHP app still runs on MySQL; this prepares the Supabase project for hosting.
--
-- Conversions: AUTO_INCREMENT -> identity, enum -> text + CHECK,
-- tinyint(1) -> smallint (keeps the app's `= 1` comparisons valid),
-- JSON longtext -> jsonb, timestamp -> timestamptz,
-- ON UPDATE current_timestamp -> set_updated_at() trigger.

CREATE OR REPLACE FUNCTION public.set_updated_at() RETURNS trigger
LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END $$;

CREATE TABLE public.users (
  user_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      varchar(50)  NOT NULL UNIQUE,
  password_hash varchar(255) NOT NULL,
  role          text NOT NULL DEFAULT 'student' CHECK (role IN ('student','teacher','admin')),
  full_name     varchar(120) NOT NULL,
  email         varchar(150),
  profile_pic   varchar(255),
  is_active     smallint NOT NULL DEFAULT 1,
  last_login    timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_users_role ON public.users (role);

CREATE TABLE public.body_systems (
  system_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  system_code varchar(30)  NOT NULL UNIQUE,
  system_name varchar(100) NOT NULL,
  icon_emoji  varchar(10),
  color_hex   varchar(10) DEFAULT '#3b82f6',
  description text,
  sort_order  integer  NOT NULL DEFAULT 0,
  is_active   smallint NOT NULL DEFAULT 1
);

CREATE TABLE public.app_settings (
  setting_key   varchar(80) PRIMARY KEY,
  setting_value text NOT NULL
);

CREATE TABLE public.achievement_rules (
  achievement_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title          varchar(100)  NOT NULL,
  metric         varchar(50)   NOT NULL,
  threshold      numeric(10,2) NOT NULL,
  is_active      smallint NOT NULL DEFAULT 1
);

CREATE TABLE public.anatomy_content (
  system_id   integer PRIMARY KEY REFERENCES public.body_systems (system_id) ON DELETE CASCADE,
  model_url   varchar(500),
  key_facts   text,
  structures  text,
  source_text text
);

CREATE TABLE public.student_profiles (
  profile_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       integer NOT NULL UNIQUE REFERENCES public.users (user_id) ON DELETE CASCADE,
  student_id    varchar(20) NOT NULL UNIQUE,
  section       varchar(60) NOT NULL,
  grade_level   varchar(20) NOT NULL,
  birth_date    date,
  guardian_name varchar(120),
  contact_no    varchar(20),
  school_year   varchar(20) NOT NULL DEFAULT '',
  created_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.teacher_profiles (
  profile_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    integer NOT NULL UNIQUE REFERENCES public.users (user_id) ON DELETE CASCADE,
  teacher_id varchar(20)  NOT NULL UNIQUE,
  subject    varchar(100) NOT NULL DEFAULT 'Science',
  department varchar(100),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.password_reset_tokens (
  token_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    integer NOT NULL REFERENCES public.users (user_id) ON DELETE CASCADE,
  token_hash varchar(64) NOT NULL UNIQUE,  -- SHA-256 hash of the raw token
  -- MySQL's implicit ON UPDATE on expires_at is deliberately not carried over:
  -- updating a token row must not extend its expiry.
  expires_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_prt_user ON public.password_reset_tokens (user_id);

CREATE TABLE public.notification_receipts (
  user_id          integer NOT NULL REFERENCES public.users (user_id) ON DELETE CASCADE,
  notification_key varchar(80) NOT NULL,
  read_at          timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, notification_key)
);

CREATE TABLE public.announcements (
  announcement_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id      integer NOT NULL REFERENCES public.users (user_id),
  title           varchar(255) NOT NULL,
  body            text NOT NULL,
  category        text NOT NULL DEFAULT 'general' CHECK (category IN ('general','lesson','quiz','urgent','event')),
  audience        varchar(200) NOT NULL DEFAULT 'all',
  is_pinned       smallint NOT NULL DEFAULT 0,
  is_published    smallint NOT NULL DEFAULT 1,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_teacher_title UNIQUE (teacher_id, title)
);
CREATE INDEX idx_announcements_pinned ON public.announcements (is_pinned);

CREATE TABLE public.announcement_reads (
  read_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  announcement_id integer NOT NULL REFERENCES public.announcements (announcement_id) ON DELETE CASCADE,
  user_id         integer NOT NULL REFERENCES public.users (user_id) ON DELETE CASCADE,
  read_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_ann_user UNIQUE (announcement_id, user_id)
);
CREATE INDEX idx_announcement_reads_user ON public.announcement_reads (user_id);

CREATE TABLE public.modules (
  module_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  system_id     integer NOT NULL REFERENCES public.body_systems (system_id),
  teacher_id    integer NOT NULL REFERENCES public.users (user_id),
  title         varchar(200) NOT NULL,
  description   text,
  thumbnail_url varchar(255),
  status        text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','archived')),
  sort_order    integer NOT NULL DEFAULT 0,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  published_at  timestamptz,
  CONSTRAINT uq_system_title UNIQUE (system_id, title)
);
CREATE INDEX idx_modules_teacher ON public.modules (teacher_id);
CREATE INDEX idx_modules_status  ON public.modules (status);

CREATE TABLE public.lessons (
  lesson_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  module_id     integer NOT NULL REFERENCES public.modules (module_id) ON DELETE CASCADE,
  teacher_id    integer NOT NULL REFERENCES public.users (user_id),
  title         varchar(200) NOT NULL,
  lesson_type   text NOT NULL DEFAULT 'reading' CHECK (lesson_type IN ('reading','video','3d_model','interactive','quiz_prep')),
  content_text  text,
  media_url     varchar(255),
  duration_mins integer,
  sort_order    integer NOT NULL DEFAULT 0,
  status        text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','archived')),
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_module_title UNIQUE (module_id, title)
);
CREATE INDEX idx_lessons_teacher ON public.lessons (teacher_id);

CREATE TABLE public.assessments (
  assessment_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  teacher_id      integer NOT NULL REFERENCES public.users (user_id),
  system_id       integer REFERENCES public.body_systems (system_id) ON DELETE SET NULL,
  module_id       integer REFERENCES public.modules (module_id) ON DELETE SET NULL,
  title           varchar(200) NOT NULL,
  assessment_type text NOT NULL DEFAULT 'quiz' CHECK (assessment_type IN ('quiz','identification','diagram','exploration','interactive','mixed')),
  instructions    text,
  time_limit_mins integer,
  passing_score   numeric(5,2) NOT NULL DEFAULT 75.00,
  max_attempts    integer NOT NULL DEFAULT 3,
  status          text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','scheduled','active','closed')),
  due_date        timestamptz,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_assessments_system  ON public.assessments (system_id);
CREATE INDEX idx_assessments_module  ON public.assessments (module_id);
CREATE INDEX idx_assessments_status  ON public.assessments (status);
CREATE INDEX idx_assessments_teacher ON public.assessments (teacher_id);

CREATE TABLE public.questions (
  question_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id integer NOT NULL REFERENCES public.assessments (assessment_id) ON DELETE CASCADE,
  question_text text NOT NULL,
  question_type text NOT NULL DEFAULT 'multiple_choice' CHECK (question_type IN ('multiple_choice','true_false','identification','fill_blank','drag_drop','hotspot','interactive')),
  image_url     varchar(255),
  hotspot_data  jsonb,  -- clickable areas for hotspot type: [{id, x, y, w, h, label}]
  points        numeric(5,2) NOT NULL DEFAULT 1.00,
  sort_order    integer NOT NULL DEFAULT 0
);
CREATE INDEX idx_questions_assessment ON public.questions (assessment_id);

CREATE TABLE public.answer_options (
  option_id   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_id integer NOT NULL REFERENCES public.questions (question_id) ON DELETE CASCADE,
  option_text varchar(500) NOT NULL,
  is_correct  smallint NOT NULL DEFAULT 0,
  sort_order  integer  NOT NULL DEFAULT 0
);
CREATE INDEX idx_answer_options_question ON public.answer_options (question_id);

